//! Custom `kafka4php` PHP SAPI (C, in `csrc/`) and raw FFI bindings to its header.
//!
//! DESIGN.md §5.1–5.3. The C ABI is `csrc/k4p_sapi.h` (bindings in [`ffi`]); this crate
//! adds only thin wrappers and the conversions between `k4p-core` types and the C
//! structs. Threading, timeouts and recycling are `k4p-php`'s job.
//!
//! Lifecycle (see the header for the full contract):
//!
//! 1. [`runtime_init`] once per process, on a thread that outlives all PHP use (the
//!    "runtime thread").
//! 2. On every other thread that runs PHP: [`thread_init`], then any number of
//!    [`execute`] calls (one at a time per thread), then [`thread_shutdown`].
//! 3. [`runtime_shutdown`] on the runtime thread after every PHP thread is done.

use std::ffi::{CString, c_void};
use std::fmt;
use std::marker::PhantomData;
use std::os::unix::ffi::OsStrExt;
use std::path::PathBuf;
use std::ptr;

use k4p_core::{ExecutionError, HandlerResult, InboundMessage, OutboundMessage, Outcome};

/// Raw bindings generated by bindgen from `csrc/k4p_sapi.h`.
#[allow(
    non_camel_case_types,
    non_upper_case_globals,
    non_snake_case,
    missing_debug_implementations,
    clippy::all
)]
pub mod ffi {
    include!(concat!(env!("OUT_DIR"), "/bindings.rs"));
}

// ---------------------------------------------------------------------------------
// InboundMessage -> C

fn c_buf(bytes: Option<&[u8]>) -> ffi::k4p_buf {
    match bytes {
        Some(b) => ffi::k4p_buf {
            data: b.as_ptr(),
            len: b.len(),
            is_null: 0,
        },
        None => ffi::k4p_buf {
            data: ptr::null(),
            len: 0,
            is_null: 1,
        },
    }
}

/// C view of an [`InboundMessage`], borrowing all its bytes. Pass [`CMessage::as_ptr`]
/// to `k4p_execute`; the message must outlive the call (the borrow guarantees it).
pub struct CMessage<'a> {
    raw: ffi::k4p_message,
    // Owns the header array `raw.headers` points into (heap buffer: stable on move).
    _headers: Vec<ffi::k4p_header>,
    _msg: PhantomData<&'a InboundMessage>,
}

impl fmt::Debug for CMessage<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("CMessage").finish_non_exhaustive()
    }
}

impl<'a> CMessage<'a> {
    pub fn new(msg: &'a InboundMessage) -> Self {
        let headers: Vec<ffi::k4p_header> = msg
            .headers
            .iter()
            .map(|(k, v)| ffi::k4p_header {
                key: c_buf(Some(k.as_bytes())),
                value: c_buf(v.as_deref()),
            })
            .collect();
        let raw = ffi::k4p_message {
            topic: c_buf(Some(msg.topic.as_bytes())),
            delivery_topic: c_buf(Some(msg.delivery_topic.as_bytes())),
            partition: msg.partition,
            offset: msg.offset,
            has_timestamp: u8::from(msg.timestamp_ms.is_some()),
            timestamp_ms: msg.timestamp_ms.unwrap_or(0),
            key: c_buf(msg.key.as_deref()),
            value: c_buf(msg.value.as_deref()),
            headers: if headers.is_empty() {
                ptr::null()
            } else {
                headers.as_ptr()
            },
            headers_len: headers.len(),
            attempt: msg.attempt,
        };
        Self {
            raw,
            _headers: headers,
            _msg: PhantomData,
        }
    }

    pub fn as_ptr(&self) -> *const ffi::k4p_message {
        &self.raw
    }
}

